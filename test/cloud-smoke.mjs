import assert from 'node:assert/strict';
import { createSupabaseApi } from '../public/supabase-api.mjs';
import { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY } from '../public/config.mjs';
let access = '';
const api = createSupabaseApi({ url: SUPABASE_URL, key: SUPABASE_PUBLISHABLE_KEY, getAccessToken: () => access });
const session = await api('sessions', { title: 'Тест подключения (можно удалить)', roles: ['Пример роли A', 'Пример роли B'] });
const path = `sessions/${session.code}`;
access = session.inviteToken;
const initial = await api(path);
const p1 = await api(path+'/join', { name: 'Тест A' });
const p2 = await api(path+'/join', { name: 'Тест B' });
await assert.rejects(() => api(path+'/action', { token: session.inviteToken, action: 'open' }));
await api(path+'/action', { token: session.token, action: 'open' });
const vote = { participantId: p1.id, participantToken: p1.token, roleId: initial.currentRoleId, round: 1, scores: [5,4,4,3,4,2] };
await api(path+'/vote', vote);
await assert.rejects(() => api(path+'/vote', vote));
await api(path+'/vote', { ...vote, participantId: p2.id, participantToken: p2.token, scores: [1,1,1,1,1,1] });
assert.deepEqual((await api(path)).results, {});
await api(path+'/action', { token: session.token, action: 'close' });
const closed = await api(path);
assert.equal(closed.leaderboard[0].score, 2.5);
for (const secret of [session.token,session.inviteToken,p1.token,p2.token]) assert.equal(JSON.stringify(closed).includes(secret), false);
access = 'not-an-invitation';
await assert.rejects(() => api(path));
await api(path+'/action', { token: session.token, action: 'finish' });
console.log('PASS: live Supabase, two voters, host-only controls, duplicate protection, hidden scores, weighted average 2.50 and session completion.');
